import axios from "axios";
import fs from "fs";
import path from "path";

function lowConfidence(value) {
  return Math.max(0, Math.min(1, value));
}

function localImageSignals(imageRelativePath) {
  const reasons = [];
  if (!imageRelativePath) {
    return { prediction: "suspicious", authenticityScore: 0.45, reasons: ["No image uploaded"] };
  }
  const fullPath = path.join(process.cwd(), imageRelativePath.replace(/^\//, ""));
  try {
    const stat = fs.statSync(fullPath);
    const ext = path.extname(fullPath).toLowerCase();
    const fileName = path.basename(fullPath).toLowerCase();
    let score = 0.8;
    if (/ai|midjourney|stable.?diffusion|dall.?e|generated|synthetic|fake/.test(fileName)) {
      score -= 0.45;
      reasons.push("Filename pattern indicates AI-generated image");
    }
    if (stat.size < 10 * 1024) {
      score -= 0.35;
      reasons.push("Very small image size");
    }
    if (stat.size > 5 * 1024 * 1024) {
      score -= 0.1;
      reasons.push("Unusually large image");
    }
    if (![".jpg", ".jpeg", ".png", ".webp", ".gif"].includes(ext)) {
      score -= 0.2;
      reasons.push("Unsupported extension pattern");
    }
    const authenticityScore = lowConfidence(score);
    const prediction = authenticityScore >= 0.65 ? "real" : authenticityScore >= 0.5 ? "suspicious" : "fake";
    return { prediction, authenticityScore, reasons };
  } catch {
    return { prediction: "suspicious", authenticityScore: 0.4, reasons: ["Image file could not be read"] };
  }
}

function localTextSignals(text) {
  const t = (text || "").trim();
  const reasons = [];
  let score = 0.85;
  if (t.length < 25) {
    score -= 0.35;
    reasons.push("Description too short");
  }
  if (/lorem ipsum|as an ai|generated by ai|this is a sample/i.test(t)) {
    score -= 0.35;
    reasons.push("Contains AI-like generic phrasing");
  }
  if (/(.)\1{8,}/.test(t.replace(/\s/g, ""))) {
    score -= 0.25;
    reasons.push("Repetitive character pattern");
  }
  if (/\b(kill|hate|abuse|stupid)\b/i.test(t)) {
    score -= 0.2;
    reasons.push("Potentially abusive wording");
  }
  if (/\b(alien|ufo|hack everything|destroy city|take over planet|ghost attack)\b/i.test(t)) {
    score -= 0.45;
    reasons.push("Unrealistic or non-civic complaint text detected");
  }
  const authenticityScore = lowConfidence(score);
  const prediction = authenticityScore >= 0.65 ? "human" : authenticityScore >= 0.5 ? "suspicious" : "ai_generated";
  return { prediction, authenticityScore, reasons };
}

async function callAi(url, payload) {
  if (!url) return null;
  try {
    const { data } = await axios.post(url, payload, { timeout: 15000 });
    return data;
  } catch {
    return null;
  }
}

export async function detectImageAuthenticity({ imageRelativePath }) {
  const local = localImageSignals(imageRelativePath);
  const service = await callAi(
    process.env.AI_IMAGE_DETECT_URL || (process.env.AI_SERVICE_URL ? `${process.env.AI_SERVICE_URL.replace(/\/$/, "")}/detect-image` : ""),
    { image_path: imageRelativePath }
  );
  if (service && typeof service === "object") {
    const authenticityScore =
      typeof service.authenticity_score === "number"
        ? lowConfidence(service.authenticity_score)
        : local.authenticityScore;
    const prediction =
      service.prediction === "real" || service.prediction === "fake" || service.prediction === "suspicious"
        ? service.prediction
        : local.prediction;
    return {
      prediction,
      authenticityScore,
      confidence: typeof service.confidence === "number" ? lowConfidence(service.confidence) : authenticityScore,
      reasons: Array.isArray(service.reasons) ? service.reasons : local.reasons,
      raw: service,
    };
  }
  return { ...local, confidence: local.authenticityScore, raw: null };
}

